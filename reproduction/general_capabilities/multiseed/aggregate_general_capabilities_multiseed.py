#!/usr/bin/env python3
"""
Aggregate multiseed general-capabilities eval results (hellaswag/mmlu/winogrande)
into mean/std and bootstrap CIs, plus a long-format CSV for plotting.

Reads the JSON records eval_v2.py writes per run:

    results/multiseed_eval/<category>/<model_label>/<benchmark>_seed<seed>.json
    {"category": ..., "model_name": ..., "model_path": ..., "benchmark": ...,
     "task_type": ..., "seed": ..., "score": ..., "timestamp": ...}

Each (category, model, benchmark) here holds 3 seeds of the SAME checkpoint
(eval-time noise from non-deterministic GPU kernels under greedy decoding),
not 3 independently-trained checkpoints -- see general_capabilities/README.md.

Usage:
    python aggregate_general_capabilities_multiseed.py --seeds 0 1 2
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np

RESULTS_ROOT = Path(__file__).resolve().parent.parent / "results" / "multiseed_eval"


def discover(seeds: List[int]) -> Dict[str, Dict[str, Dict[str, List[dict]]]]:
    """{category: {model_label: {benchmark: [record, ...]}}}"""
    data: Dict[str, Dict[str, Dict[str, List[dict]]]] = {}
    if not RESULTS_ROOT.exists():
        return data
    for category_dir in sorted(RESULTS_ROOT.iterdir()):
        if not category_dir.is_dir():
            continue
        category = category_dir.name
        for model_dir in sorted(category_dir.iterdir()):
            if not model_dir.is_dir():
                continue
            model = model_dir.name
            for seed in seeds:
                for json_path in sorted(model_dir.glob(f"*_seed{seed}.json")):
                    record = json.loads(json_path.read_text())
                    benchmark = record["benchmark"]
                    data.setdefault(category, {}).setdefault(model, {}).setdefault(benchmark, []).append(record)
    return data


def bootstrap_ci(values: List[float], n_resamples: int = 10000, alpha: float = 0.05, rng=None) -> Optional[tuple]:
    if len(values) < 2:
        return None
    rng = rng or np.random.default_rng(12345)
    arr = np.asarray(values)
    resampled_means = rng.choice(arr, size=(n_resamples, len(arr)), replace=True).mean(axis=1)
    lo, hi = np.percentile(resampled_means, [100 * alpha / 2, 100 * (1 - alpha / 2)])
    return float(lo), float(hi)


def write_csv(data: Dict[str, Dict[str, Dict[str, List[dict]]]], path: Path) -> None:
    with path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["category", "model", "benchmark", "seed", "score"])
        for category, models in data.items():
            for model, benchmarks in models.items():
                for benchmark, records in benchmarks.items():
                    for r in records:
                        writer.writerow([category, model, benchmark, r["seed"], r["score"]])
    print(f"Wrote: {path}")


def write_python_module(data: Dict[str, Dict[str, Dict[str, List[dict]]]], path: Path) -> None:
    with path.open("w") as f:
        f.write('"""Auto-generated by aggregate_general_capabilities_multiseed.py. Do not hand-edit."""\n\n')
        f.write("GENERAL_CAPABILITIES_MULTISEED = {\n")
        for category, models in sorted(data.items()):
            f.write(f"    {category!r}: {{\n")
            for model, benchmarks in sorted(models.items()):
                f.write(f"        {model!r}: {{\n")
                for benchmark, records in sorted(benchmarks.items()):
                    vals = [r["score"] for r in sorted(records, key=lambda r: r["seed"])]
                    mean = float(np.mean(vals))
                    std = float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0
                    ci = bootstrap_ci(vals)
                    f.write(
                        f"            {benchmark!r}: {{'values': {vals!r}, 'mean': {mean!r}, "
                        f"'std': {std!r}, 'ci95': {ci!r}}},\n"
                    )
                f.write("        },\n")
            f.write("    },\n")
        f.write("}\n")
    print(f"Wrote: {path}")


def format_report(data: Dict[str, Dict[str, Dict[str, List[dict]]]]) -> str:
    lines = []
    for category, models in sorted(data.items()):
        for model, benchmarks in sorted(models.items()):
            for benchmark, records in sorted(benchmarks.items()):
                vals = [r["score"] for r in records]
                mean = np.mean(vals)
                std = np.std(vals, ddof=1) if len(vals) > 1 else 0.0
                ci = bootstrap_ci(vals)
                ci_str = f", CI95=[{ci[0]:.4f},{ci[1]:.4f}]" if ci else ""
                lines.append(
                    f"{category:10s} {model:26s} {benchmark:12s} "
                    f"{mean:.4f}±{std:.4f} (n={len(vals)}{ci_str})"
                )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Aggregate multiseed general-capabilities eval results.")
    parser.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    parser.add_argument("--out", type=Path, default=Path(__file__).with_name("results_multiseed.py"))
    parser.add_argument("--csv-out", type=Path, default=Path(__file__).with_name("results_multiseed.csv"))
    args = parser.parse_args()

    data = discover(args.seeds)
    if not data:
        print(f"[WARN] No results found under {RESULTS_ROOT}")
        return

    print("\n===================== MEAN ± STD (bootstrap 95% CI) =====================")
    print(format_report(data))

    write_csv(data, args.csv_out)
    write_python_module(data, args.out)


if __name__ == "__main__":
    main()
